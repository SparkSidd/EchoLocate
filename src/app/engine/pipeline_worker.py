"""
EchoLocate — Real-Time Pipeline Worker & Processing Loop
========================================================
Coordinates frame ingestion, input validation, multi-method localization,
temporal stabilization, and WebSocket result broadcasting.
"""

from __future__ import annotations

import logging
import queue
import threading
import time
from dataclasses import dataclass, field
from typing import Any, Callable

import numpy as np

from src.app.audit.data_provenance import DataProvenance, ProvenanceMetadata
from src.app.engine.input_validator import validate_audio_frame
from src.app.engine.method_registry import EchoLocateMethodRegistry, MethodLocalizationOutput
from src.app.engine.temporal_tracker import CausalTemporalTracker, TrackedEstimate

logger = logging.getLogger(__name__)


@dataclass
class PipelineFramePacket:
    """Input frame payload passed into the localization worker."""
    frame_index: int
    audio_data: np.ndarray
    sample_rate: int
    timestamp_ingested: float
    provenance_meta: ProvenanceMetadata
    ground_truth_xy: tuple[float, float] | None = None


@dataclass
class LocalizationResultPacket:
    """Output packet generated by the pipeline for UI and logging."""
    frame_index: int
    timestamp_ingested: float
    timestamp_processed: float
    processing_latency_ms: float
    queue_delay_ms: float
    real_time_factor: float
    provenance: ProvenanceMetadata
    method_id: str
    raw_estimate_xy: tuple[float, float]
    smoothed_estimate_xy: tuple[float, float]
    ground_truth_xy: tuple[float, float] | None
    error_m: float | None
    confidence: float
    spatial_contrast: float
    status: str
    intermediate_info: dict[str, Any] = field(default_factory=dict)
    heatmap_2d: list[list[float]] | None = None


class RealTimePipelineWorker:
    """Thread-safe worker executing real-time localization on incoming audio frames."""

    def __init__(
        self,
        method_registry: EchoLocateMethodRegistry,
        temporal_tracker: CausalTemporalTracker,
        active_method: str = "M2_Raw_SRP",
        frame_duration_s: float = 0.20,
    ) -> None:
        self.registry = method_registry
        self.tracker = temporal_tracker
        self.active_method = active_method
        self.frame_duration_s = frame_duration_s

        self.input_queue: queue.Queue[PipelineFramePacket] = queue.Queue(maxsize=50)
        self.result_callbacks: list[Callable[[LocalizationResultPacket], None]] = []

        self._is_running = False
        self._thread: threading.Thread | None = None
        self.dropped_frames = 0
        self.processed_frames = 0

    def set_active_method(self, method_id: str) -> None:
        """Switch active localization algorithm."""
        self.active_method = method_id

    def register_result_callback(self, cb: Callable[[LocalizationResultPacket], None]) -> None:
        """Register listener for localized output packets."""
        self.result_callbacks.append(cb)

    def submit_frame(self, packet: PipelineFramePacket) -> bool:
        """Submit frame to processing queue. Drops frame if queue is full to prevent latency buildup."""
        try:
            self.input_queue.put_nowait(packet)
            return True
        except queue.Full:
            self.dropped_frames += 1
            logger.warning("Pipeline queue overrun! Dropped frame #%d", packet.frame_index)
            return False

    def start(self) -> None:
        """Start worker thread."""
        if self._is_running:
            return
        self._is_running = True
        self._thread = threading.Thread(target=self._worker_loop, daemon=True)
        self._thread.start()
        logger.info("RealTimePipelineWorker started successfully.")

    def stop(self) -> None:
        """Stop worker thread."""
        self._is_running = False
        if self._thread and self._thread.is_alive():
            self._thread.join(timeout=1.0)
        logger.info("RealTimePipelineWorker stopped.")

    def _worker_loop(self) -> None:
        while self._is_running:
            try:
                packet = self.input_queue.get(timeout=0.1)
            except queue.Empty:
                continue

            t_start = time.perf_counter()
            queue_delay_ms = (t_start - packet.timestamp_ingested) * 1000.0

            # 1. Validate Input Signal
            val_res = validate_audio_frame(packet.audio_data, expected_channels=len(self.registry.mics))
            if not val_res.is_valid:
                continue

            # 2. Execute Localization Method
            loc_out: MethodLocalizationOutput = self.registry.execute_method(self.active_method, packet.audio_data)

            # 3. Causal Temporal Tracking
            tracked: TrackedEstimate = self.tracker.update(loc_out.pred_x, loc_out.pred_y, confidence=loc_out.confidence)

            t_end = time.perf_counter()
            proc_lat_ms = (t_end - t_start) * 1000.0
            rtf = (proc_lat_ms / 1000.0) / max(1e-4, self.frame_duration_s)

            # Compute error if ground truth is available
            err_m = None
            if packet.ground_truth_xy is not None:
                err_m = float(np.hypot(tracked.smoothed_x - packet.ground_truth_xy[0], tracked.smoothed_y - packet.ground_truth_xy[1]))

            heatmap_json = loc_out.heatmap_2d.tolist() if loc_out.heatmap_2d is not None else None

            out_packet = LocalizationResultPacket(
                frame_index=packet.frame_index,
                timestamp_ingested=packet.timestamp_ingested,
                timestamp_processed=time.time(),
                processing_latency_ms=proc_lat_ms,
                queue_delay_ms=queue_delay_ms,
                real_time_factor=rtf,
                provenance=packet.provenance_meta,
                method_id=self.active_method,
                raw_estimate_xy=(tracked.raw_x, tracked.raw_y),
                smoothed_estimate_xy=(tracked.smoothed_x, tracked.smoothed_y),
                ground_truth_xy=packet.ground_truth_xy,
                error_m=err_m,
                confidence=loc_out.confidence,
                spatial_contrast=loc_out.spatial_contrast,
                status=loc_out.status,
                intermediate_info=loc_out.intermediate_info,
                heatmap_2d=heatmap_json,
            )

            self.processed_frames += 1
            for cb in self.result_callbacks:
                try:
                    cb(out_packet)
                except Exception as e:
                    logger.error("Callback error: %s", e)

            self.input_queue.task_done()
